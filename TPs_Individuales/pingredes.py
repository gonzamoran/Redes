import matplotlib.pyplot as plt
import numpy as np

tiempos = []

with open("ping.txt", "r") as f:
  for linea in f:
    if "time=" in linea:
      resto = linea.split("time=")[1]
      tiempo_str = resto.split()[0] # me quedo solo con el numero del tiempo y saco el ms\n

      tiempo = float(tiempo_str)
      tiempos.append(tiempo)


array_tiempos = np.array(tiempos)

plt.figure(figsize=(10, 5))

plt.plot( array_tiempos, linestyle='-')
plt.title('RTT Ping Twitter', fontsize=14, fontweight='bold')
plt.xlabel('Numero de paquete')
plt.ylabel('Tiempo (ms)')


plt.grid(True, linestyle=':', alpha=0.6)
plt.legend()

plt.show()

array_tiempos = np.array(tiempos)
eje_x = np.arange(1, len(array_tiempos) + 1) / 60

plt.figure(figsize=(10, 5))

plt.plot(eje_x, array_tiempos, linestyle='-')

plt.yscale('log')
plt.xscale('log')
plt.title('RTT Ping Twitter (log)', fontsize=14, fontweight='bold')
plt.xlabel('Minutos -- Log')
plt.ylabel('Tiempo (ms) -- Log')


plt.grid(True, linestyle=':', alpha=0.6, which='both')
plt.legend()

plt.show()